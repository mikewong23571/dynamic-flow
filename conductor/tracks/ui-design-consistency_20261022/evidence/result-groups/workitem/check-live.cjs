const {chromium,expect}=require('@playwright/test');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const checks=[];
 for(const [width,height] of [[1440,900],[1024,768]]){
  const page=await browser.newPage({viewport:{width,height}});
  const writes=[];page.on('request',r=>{if(r.url().includes('/api/items/')&&r.method()!=='GET')writes.push(r.url())});
  await page.goto('http://127.0.0.1:4320');
  await page.locator('.sidebar').getByRole('button',{name:'工作项',exact:true}).click();
  await page.getByRole('button',{name:'打开工作项 CVE-2025-27516:SCC-source-review',exact:true}).click();
  const detail=page.getByRole('article',{name:'工作项详情'});
  await detail.getByRole('combobox',{name:'推进轮次',exact:true}).waitFor();
  await page.waitForTimeout(700);
  await page.screenshot({path:`${__dirname}/after-${width}.png`});
  await detail.getByRole('button',{name:/^完成条件/}).click();
  await expect(detail.getByRole('tab',{name:/^完成条件/})).toHaveAttribute('data-state','active');
  await detail.getByRole('tab',{name:'成果与过程',exact:true}).click();
  const round=detail.getByRole('combobox',{name:'推进轮次',exact:true});
  const latest=await round.inputValue();
  const options=await round.locator('option').evaluateAll(es=>es.map(e=>({value:e.value,text:e.textContent})));
  await round.selectOption(options.at(-1).value);
  await expect(round).toHaveValue(options.at(-1).value);
  await round.selectOption(latest);
  await detail.getByRole('button',{name:/呈现核查结论/}).click();
  await detail.getByRole('button',{name:'引用',exact:true}).click();
  await expect(page.getByRole('menuitem',{name:'完成条件',exact:true})).toBeVisible();
  await expect(page.getByRole('menuitem',{name:'证据材料',exact:true})).toBeVisible();
  await page.getByRole('menuitem',{name:'完成条件',exact:true}).click();
  const criteria=detail.getByRole('tab',{name:/^完成条件/});
  await expect(criteria).toHaveAttribute('data-state','active');
  await expect(detail.getByRole('button',{name:'结项',exact:true})).toBeDisabled();
  const evidence=detail.locator('textarea').first();
  const prior=await evidence.inputValue();
  await evidence.fill('本地浏览器草稿，不提交');
  await detail.getByRole('button',{name:'选择成果',exact:true}).click();
  await detail.getByRole('button',{name:'返回完成条件',exact:true}).click();
  await expect(evidence).toHaveValue('本地浏览器草稿，不提交');
  await evidence.fill(prior);
  await page.screenshot({path:`${__dirname}/criteria-${width}.png`});
  await detail.getByRole('button',{name:'目标与方法',exact:true}).click();
  const modal=page.getByRole('dialog',{name:'目标与处理方法',exact:true});
  await expect(modal).toBeVisible();
  await expect(modal.getByRole('button',{name:'更换处理方法',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await detail.getByRole('tab',{name:'业务记录',exact:true}).click();
  await expect(detail).toContainText('等待新流水线研究漏洞材料。');
  await detail.getByRole('tab',{name:'成果与过程',exact:true}).click();
  await detail.getByRole('button',{name:'继续处理',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'准备本次执行',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.screenshot({path:`${__dirname}/report-${width}.png`});
  const shape=await detail.evaluate(el=>({overflow:document.documentElement.scrollWidth>innerWidth,content:Array.from(el.querySelectorAll('.item-retained-artifact')).find(e=>e.getBoundingClientRect().height>0)?.getBoundingClientRect().top,body:Array.from(el.querySelectorAll('.artifact-value')).find(e=>e.getBoundingClientRect().height>0)?.getBoundingClientRect().top}));
  checks.push({width,rounds:options,historySwitch:true,referenceMenu:true,criterionReturnDraft:true,completeDisabled:true,methodDialog:true,summaryPreserved:true,continueOpensPreparation:true,writes,shape});
  await page.close();
 }
 fs.writeFileSync(`${__dirname}/checks.json`,JSON.stringify(checks,null,2));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
